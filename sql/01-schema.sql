-- 文字面试答案表 (InterviewAnswerEntity)
CREATE TABLE interview_answers
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT       NOT NULL,
    session_id       BIGINT       NOT NULL,
    question_index   INTEGER,
    question         TEXT,
    category         VARCHAR(255),
    user_answer      TEXT,
    score            INTEGER,
