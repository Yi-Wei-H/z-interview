-- RAG 聊天会话表 (RagChatSessionEntity)
CREATE TABLE rag_chat_sessions
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL,
    title         VARCHAR(255) NOT NULL,
    status        VARCHAR(20),
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6),
    message_count INTEGER,
    is_pinned     BOOLEAN DEFAULT false,
    PRIMARY KEY (id)
);

-- RAG 聊天消息表 (RagChatMessageEntity)
CREATE TABLE rag_chat_messages
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT       NOT NULL,
    session_id    BIGINT       NOT NULL,
    type          VARCHAR(20)  NOT NULL,
    content       TEXT         NOT NULL,
    message_order INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6),
    completed     BOOLEAN,
    PRIMARY KEY (id),
    CONSTRAINT fk_rag_chat_messages_session FOREIGN KEY (session_id) REFERENCES rag_chat_sessions (id)
