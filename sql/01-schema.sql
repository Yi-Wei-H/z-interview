-- RAG 会话-知识库关联表 (@ManyToMany @JoinTable, 无独立主键)
-- 设计裁定：不加 user_id——关联经会话（user_id）与知识库（user_id）双亲间接隔离，
-- 绑定时服务层校验 KB 属主，保证关联只会发生在同一用户的两者之间
CREATE TABLE rag_session_knowledge_bases
(
    session_id        BIGINT NOT NULL,
    knowledge_base_id BIGINT NOT NULL,
    CONSTRAINT fk_rag_session_kb_session FOREIGN KEY (session_id) REFERENCES rag_chat_sessions (id),
    CONSTRAINT fk_rag_session_kb_knowledge_base FOREIGN KEY (knowledge_base_id) REFERENCES knowledge_bases (id)
);

-- LLM Provider 配置表 (LlmProviderEntity, 主键为 "userId:用户输入ID", 按用户隔离)
CREATE TABLE llm_provider_config
(
    id                   VARCHAR(64)   NOT NULL,
